import { describe, expect, it } from 'vitest';
import { createExcludeMatcher } from '../../src/guard/exclude';
import { DEFAULT_MAX_LINES, looksGenerated, MAX_BYTES, sizeProblem } from '../../src/guard/size';

describe('exclusions', () => {
  const matcher = createExcludeMatcher({ patterns: ['**/secrets/**', 'build/**', ' '] });

  it.each([
    '.env',
    'app/.env.local',
    'certs/server.pem',
    'deploy/prod.key',
    'home/id_rsa',
    'aws/credentials',
    'infra/main.tfvars',
    'CONFIG/.ENV',
  ])('always refuses secret-looking file %s', (relPath) => {
    expect(createExcludeMatcher({ patterns: [] })({ relPath })).toBe(true);
  });

  it('matches setting globs on relative and absolute paths', () => {
    expect(matcher({ relPath: 'src/secrets/db.ts' })).toBe(true);
    expect(matcher({ relPath: 'build/out.js' })).toBe(true);
    expect(matcher({ absPath: '/tmp/x/secrets/a.ts' })).toBe(true);
    expect(matcher({ absPath: '/tmp/work/.env' })).toBe(true);
  });

  it('allows ordinary files', () => {
    expect(matcher({ relPath: 'src/app.ts', absPath: '/w/src/app.ts' })).toBe(false);
    expect(matcher({})).toBe(false);
  });

  it('applies .logiclensignore in gitignore syntax', () => {
    const m = createExcludeMatcher({ patterns: [], ignoreText: 'vendor/\n*.gen.ts\n!keep.gen.ts' });
    expect(m({ relPath: 'vendor/lib.js' })).toBe(true);
    expect(m({ relPath: 'src/a.gen.ts' })).toBe(true);
    expect(m({ relPath: 'src/keep.gen.ts' })).toBe(false);
    // The ignore file only applies inside the workspace.
    expect(m({ absPath: '/outside/vendor/lib.js' })).toBe(false);
  });
});

describe('size limits', () => {
  it('accepts files within the limits', () => {
    expect(sizeProblem(['a'], 1, DEFAULT_MAX_LINES)).toBeUndefined();
  });

  it('refuses too many lines', () => {
    expect(sizeProblem(new Array(11).fill(''), 11, 10)).toMatch(/11 lines/);
  });

  it('refuses too many bytes', () => {
    expect(sizeProblem(['a'], MAX_BYTES + 1, DEFAULT_MAX_LINES)).toMatch(/200 KB/);
  });

  it('flags minified and generated files', () => {
    expect(looksGenerated(['x'.repeat(1001)])).toBe(true);
    expect(looksGenerated(['// @generated by protoc'])).toBe(true);
    expect(looksGenerated(['// Code generated. DO NOT EDIT.'])).toBe(true);
    expect(looksGenerated(['const a = 1;'])).toBe(false);
    expect(looksGenerated(['', '', '', '', '', '// @generated'])).toBe(false);
  });
});
